// Copy for the Tokens group on a deck (handoff `design_handoff_the99_tokens`, R2).
// Voice is refresh.ts's: labels and figures, every count with its noun, no verdict words.
// Reused unchanged: priceCopy.tag.*, priceCopy.strip.*, exportLinkOutCopy.shopping.

const n = (x: number) => x.toLocaleString("en-US");
const cards = (x: number) => (x === 1 ? "1 card" : `${n(x)} cards`);

export const tokensCopy = {
  group: {
    label: "Tokens",
    /** Header note (desktop) / sub-line (phone). Says once that tokens aren't the deck. */
    note: (makers: number) => `not in the 99 · from ${cards(makers)}`,
    noteFailed: "not in the 99",
    failed: "Tokens couldn’t be read just now.",
  },

  /** No token-read marker for the account yet. Said once, at the head of the group. */
  unknown: {
    body: "Your collection hasn’t been read for tokens yet. Press I have one on the ones you own, or upload your collection again and they’ll be read from it.",
    action: "Upload your collection",
  },

  row: {
    type: (type: string, pt: string | null) => (pt ? `${type} · ${pt}` : type),
    from: (first: string, count: number) => (count === 1 ? `from ${first}` : `from ${first} and ${n(count - 1)} more`),
    /** Ownership fact, on upload-read tokens only. Never a verdict word, never --warning. */
    owned: "in your collection",
    join: "Add to Shopping",
    joined: "✓ In Shopping",
    /** Manual ownership: the same record an upload writes, source "manual". */
    have: "I have one",
    haveOn: "✓ I have one",
    haveAria: (name: string) => `Mark the ${name} token as in your collection`,
    haveOffAria: (name: string) => `Unmark the ${name} token`,
    joinAria: (name: string) => `Add the ${name} token to this deck’s Shopping list`,
    leaveAria: (name: string) => `Take the ${name} token off this deck’s Shopping list`,
    toggleAria: (name: string, count: number) => `${name} token, made by ${cards(count)}`,
    /** A press that did not land (the switch went off, or the deck stopped making the token). */
    refused: "We couldn’t save that. The token is unchanged.",
  },

  makers: {
    label: (count: number) => `Generated by ${cards(count)}`,
    scrolls: "A–Z · scrolls",
    printing: (code: string, cost: string, printings: number) =>
      `pictured and sent: ${code} · ${cost} · cheapest of ${n(printings)} ${printings === 1 ? "printing" : "printings"}`,
    /** Mana Pool's product is not the printing pictured (their set and number differ from Scryfall's). */
    sent: (code: string, cost: string, printings: number) =>
      `sent: ${code} · ${cost} · cheapest of ${n(printings)} ${printings === 1 ? "printing" : "printings"}`,
    /** Mana Pool cannot place the number exactly, so the link names the token alone. */
    sentByName: (cost: string, printings: number) =>
      `sent by name · ${cost} · cheapest of ${n(printings)} ${printings === 1 ? "printing" : "printings"}`,
  },
} as const;
