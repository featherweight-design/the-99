// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { act, cleanup, fireEvent, render, screen } from "@testing-library/react";

const stub = vi.hoisted(() => ({ held: vi.fn(), open: vi.fn() }));

vi.mock("../../app/decks/token-actions", () => ({ setTokenHeld: stub.held, setTokenJoined: vi.fn() }));
vi.mock("../cards/card-detail-provider", () => ({
  useCardDetail: () => ({ open: stub.open }),
  useCardIntent: () => ({}),
}));

import { DeckTokensProvider } from "./deck-tokens-context";
import { TokenDeckBox } from "./token-deck-box";
import type { DeckToken, DeckTokensRead } from "../../lib/tokens/read";

const DECK = "00000000-0000-4000-8000-0000000000d1";
const maker = (n: number) => ({ oracleId: `m${n}`, name: `Maker ${n}`, imageUri: null });
const token = (over: Partial<DeckToken> = {}): DeckToken => ({
  oracleId: "t1", name: "Food", typeLine: "Token Artifact — Food", colors: [], power: null, toughness: null,
  oracleText: null, makers: [maker(1), maker(2)], state: "not", source: null, joined: false, picture: null, printingPick: null, price: null, ...over,
});
const read = (tokens: DeckToken[]): DeckTokensRead => ({ status: "ok", read: true, tokens, makerCount: 2, newestPriceAsOf: null });
const draw = (tokens: DeckToken[], id = "t1", onSelectCard?: (id: string) => void) =>
  render(<DeckTokensProvider deckId={DECK} read={read(tokens)}><TokenDeckBox oracleId={id} onSelectCard={onSelectCard} /></DeckTokensProvider>);

beforeEach(() => {
  stub.held.mockReset();
  stub.held.mockResolvedValue({ ok: true });
});
afterEach(cleanup);

describe("TokenDeckBox", () => {
  it("draws nothing outside a deck, for a failed read, and for a token the deck lacks", () => {
    expect(render(<TokenDeckBox oracleId="t1" />).container.innerHTML).toBe("");
    cleanup();
    expect(render(<DeckTokensProvider deckId={DECK} read={{ status: "failed" }}><TokenDeckBox oracleId="t1" /></DeckTokensProvider>).container.innerHTML).toBe("");
    cleanup();
    expect(draw([token()], "other").container.innerHTML).toBe("");
  });

  it("holds I have one, the cards that make the token, and nothing about Shopping", async () => {
    draw([token()]);
    expect(screen.getByText("In this deck")).toBeTruthy();
    expect(screen.getByText("Generated by 2 cards")).toBeTruthy();
    expect(screen.getByText("Maker 1")).toBeTruthy();
    await act(async () => { fireEvent.click(screen.getByRole("button", { name: "Mark the Food token as in your collection" })); });
    expect(stub.held).toHaveBeenCalledWith(DECK, "t1", true);
    expect(screen.queryByText(/Shopping/)).toBeNull();
  });

  it("unmarks a hand mark from here, the one place the tile no longer does", async () => {
    draw([token({ state: "owned", source: "manual" })]);
    const press = screen.getByRole("button", { name: "Unmark the Food token" });
    expect(press.textContent).toBe("✓ I have one");
    expect(press.getAttribute("aria-pressed")).toBe("true");
    await act(async () => { fireEvent.click(press); });
    expect(stub.held).toHaveBeenCalledWith(DECK, "t1", false);
  });

  it("offers no hand mark when an upload or a precon holds the token", () => {
    for (const source of ["upload", "precon"] as const) {
      draw([token({ state: "owned", source })]);
      expect(screen.queryByRole("button", { name: /Mark the Food|Unmark the Food/ })).toBeNull();
      expect(screen.getByText("Generated by 2 cards")).toBeTruthy();
      cleanup();
    }
  });

  it("says a token no card makes is from no card, and offers no hand mark either way", () => {
    draw([token({ makers: [], joined: true })]);
    expect(screen.getByText("from no card in this deck")).toBeTruthy();
    expect(screen.queryByRole("button")).toBeNull();
    expect(screen.queryByText(/Generated by/)).toBeNull();
  });

  it("says a refused press as a deck toast naming the token", async () => {
    stub.held.mockResolvedValue({ ok: false });
    draw([token()]);
    await act(async () => { fireEvent.click(screen.getByRole("button", { name: "Mark the Food token as in your collection" })); });
    // The deck's toast (outside this sheet) and the same refusal said inside the dialog for a screen reader held in it.
    const alerts = screen.getAllByRole("alert");
    expect(alerts.map((a) => a.textContent)).toContain("We couldn’t save that. The token is unchanged.Food token");
    const inBox = alerts.find((a) => a.closest("[data-token-deck-box]"));
    expect(inBox?.textContent).toBe("We couldn’t save that. The token is unchanged. Food token");
    expect(inBox?.className).toContain("sr-only");
  });

  it("opens a maker through the sheet's own trail, so Close returns to the token", () => {
    const select = vi.fn();
    draw([token()], "t1", select);
    fireEvent.click(screen.getByText("Maker 2"));
    expect(select).toHaveBeenCalledWith("m2");
    // The provider's open() clears the trail, which is what a maker opened from a deck page wants and this does not.
    expect(stub.open).not.toHaveBeenCalled();
  });

  it("opens a maker through the provider where no sheet keeps a trail", () => {
    draw([token()]);
    fireEvent.click(screen.getByText("Maker 2"));
    expect(stub.open).toHaveBeenCalled();
  });

  it("keeps one token's refusal out of another token's dialog, even when they share a name", async () => {
    stub.held.mockResolvedValue({ ok: false });
    const haste = token({ oracleId: "g1", name: "Goblin", oracleText: "Haste" });
    const menace = token({ oracleId: "g2", name: "Goblin", oracleText: "Menace" });
    const { rerender } = render(<DeckTokensProvider deckId={DECK} read={read([haste, menace])}><TokenDeckBox oracleId="g1" /></DeckTokensProvider>);
    await act(async () => { fireEvent.click(screen.getByRole("button", { name: "Mark the Goblin token as in your collection" })); });
    expect(document.querySelector("[data-token-deck-box] [role=alert]")).not.toBeNull();
    // Paging to the other Goblin: the refusal belongs to the first, whatever the name.
    rerender(<DeckTokensProvider deckId={DECK} read={read([haste, menace])}><TokenDeckBox oracleId="g2" /></DeckTokensProvider>);
    expect(document.querySelector("[data-token-deck-box] [role=alert]")).toBeNull();
  });
});
