/**
 * Downloads Scryfall's mana symbols into `public/mana/` and writes the manifest
 * the renderer checks before reaching for one. Touches no database and needs no
 * secrets.
 *
 * The five WUBRG files already committed there came from the same place — the
 * filter chassis draws them — so this is that set extended to every symbol a
 * mana cost can contain: generics, X/Y/Z, colorless, snow, the hybrids, the
 * twobrids and the Phyrexians.
 *
 * Only `appears_in_mana_costs` symbols are taken. Scryfall's symbology also
 * carries tap, untap, energy, loyalty and the rest, none of which can ever
 * reach `parseManaCost`, and a file nothing renders is a file nobody maintains.
 *
 * The manifest exists because Scryfall's list GROWS. A set introducing a new
 * symbol lands in the weekly catalog refresh, while these assets only move when
 * someone runs this script — so the renderer has to be able to tell a symbol it
 * has art for from one it does not, and fall back rather than draw a blank box.
 * Re-run after a set with a new symbol:
 *
 *   pnpm fetch:mana
 */
import { readdir, unlink, writeFile } from "node:fs/promises";
import { writeManaSprite } from "./build-mana-sprite";

import { manaSymbolSlug } from "../src/lib/cards/mana-symbols";
import { SCRYFALL_HEADERS } from "../src/lib/scryfall/http";

const SYMBOLOGY = "https://api.scryfall.com/symbology";
const OUT_DIR = "public/mana";
const MANIFEST = "src/lib/cards/mana-symbol-slugs.ts";

type CardSymbol = { symbol: string; svg_uri: string; appears_in_mana_costs: boolean };

async function main(): Promise<void> {
  const res = await fetch(SYMBOLOGY, { headers: SCRYFALL_HEADERS });
  if (!res.ok) throw new Error(`Symbology ${res.status} ${res.statusText}`);
  const { data } = (await res.json()) as { data: CardSymbol[] };
  const symbols = data.filter((s) => s.appears_in_mana_costs);
  if (symbols.length < 50) {
    throw new Error(`Read ${symbols.length} cost symbols, expected at least 50 — shape changed?`);
  }

  const slugs: string[] = [];
  for (const symbol of symbols) {
    const slug = manaSymbolSlug(symbol.symbol.replace(/[{}]/g, ""));
    // Scryfall names its own files the way `manaSymbolSlug` does, so a slug that
    // does not match the remote basename means the two have drifted and the
    // renderer would ask for a file this script never wrote.
    const remote = symbol.svg_uri.split("/").pop()?.replace(/\.svg$/, "");
    if (slug !== remote) throw new Error(`${symbol.symbol}: slug ${slug} but Scryfall says ${remote}`);

    const svg = await fetch(symbol.svg_uri, { headers: { "User-Agent": SCRYFALL_HEADERS["User-Agent"] } });
    if (!svg.ok) throw new Error(`${symbol.symbol}: ${svg.status} ${svg.statusText}`);
    const body = await svg.text();
    if (!body.includes("<svg")) throw new Error(`${symbol.symbol}: not an SVG`);
    await writeFile(`${OUT_DIR}/${slug}.svg`, body);
    slugs.push(slug);
  }

  slugs.sort();
  // A symbol Scryfall dropped, or no longer prints in a cost, leaves its old file behind. The sheet
  // is built from the files on disk, so a stale one would add a cell the manifest does not hold and
  // shift every pip after it onto its neighbour's symbol. Removed here, before the sheet is built.
  const current = new Set(slugs);
  for (const file of await readdir(OUT_DIR)) {
    if (!file.endsWith(".svg") || file === "sprite.svg") continue;
    if (!current.has(file.slice(0, -4))) {
      await unlink(`${OUT_DIR}/${file}`);
      console.log(`Removed ${OUT_DIR}/${file}: no longer a cost symbol.`);
    }
  }
  await writeFile(
    MANIFEST,
    [
      "// Generated by `pnpm fetch:mana`. Do not edit by hand.",
      "//",
      "// One slug per file in `public/mana/`. A symbol absent from this set has no",
      "// art committed, and the renderer draws its colored pip instead.",
      "",
      "export const MANA_SYMBOL_SLUGS: ReadonlySet<string> = new Set([",
      ...slugs.map((s) => `  ${JSON.stringify(s)},`),
      "]);",
      "",
    ].join("\n"),
  );

  console.log(`Wrote ${slugs.length} symbols to ${OUT_DIR}/ and ${MANIFEST}.`);
  // The one file the app actually loads, rebuilt from the files just written.
  console.log(`Rebuilt the sprite from ${await writeManaSprite()} symbols.`);
}

main().catch((err) => { console.error(err); process.exit(1); });
